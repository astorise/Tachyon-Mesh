"""Official Python SDK bindings for Tachyon Mesh FaaS guests.

``wit_world/``, ``componentize_py_async_support/``, ``componentize_py_types.py``,
and ``poll_loop.py`` (installed as top-level sibling modules, not nested
under this package -- componentize-py's generated imports, e.g.
``from componentize_py_types import ...``, are absolute) are real Component
Model guest bindings generated by componentize-py
(bytecodealliance/componentize-py) from ``wit/tachyon.wit`` -- a vendored,
byte-for-byte copy of ``sdk/wit/tachyon.wit`` kept in sync by
``scripts/check_wit_sdk_sync.sh``. This module re-exports the
``kv-partition`` interface's ``Table`` resource under a more ergonomic
name and converts ``batch_set``/``get_range`` to/from plain Python dicts.

Regenerate the generated files after any ``kv-partition`` WIT change with::

    componentize-py -d wit -w kv-consumer bindings .

Every ``Table`` method below only has a real implementation once this
package is itself bundled into an actual guest component --
componentize-py's own ``componentize`` step swaps the generated
``NotImplementedError`` stub bodies for real Component Model ABI calls
when it detects which imports your guest app actually uses. The SDK's
``kv-consumer`` world only describes imports: a deployable Tachyon guest
must also export ``tachyon:mesh/handler@2.0.0``. The repository's
``tests/sdk-wasm/build-and-test.sh`` composes that world, builds a Python
guest with this SDK and runs a KV round-trip against core-host.

Calling a ``Table`` method directly under plain CPython (i.e. without that
``componentize`` step) raises ``NotImplementedError`` by design -- the same
way the Rust and Go SDKs' bindings only resolve once linked into a real
Wasmtime component instantiation. None of the three SDKs is a standalone
client library; all three are guest-side bindings.

Example:

    from tachyon_mesh_sdk import Table

    context_table = Table("viking-context")
    context_table.batch_set({
        "node:1": b"data1",
        "node:2": b"data2",
    })
    history = context_table.get_range(
        "timestamp:20260512T0000", "timestamp:20260512T2359", 50, 0,
    )
"""

from typing import Dict, Optional

from wit_world.imports.kv_partition import Table as _RawTable

__version__ = "1.0.0"

__all__ = ["Table"]


class Table:
    """A handle to a named key-value partition backed by redb on the host."""

    def __init__(self, name: str) -> None:
        self._inner = _RawTable(name)

    def get(self, key: str) -> bytes:
        """Raises ``componentize_py_types.Err(str)`` if the host call fails."""
        return self._inner.get(key)

    def set(self, key: str, value: bytes) -> None:
        """Raises ``componentize_py_types.Err(str)`` if the host call fails."""
        self._inner.set(key, value)

    def compare_and_set(self, key: str, expected: Optional[bytes], value: bytes) -> bool:
        """Atomically swaps value in if the current value matches expected.

        ``expected=None`` means "key must not exist yet". Returns whether
        the swap took place. Raises ``componentize_py_types.Err(str)`` if
        the host call fails.
        """
        return self._inner.compare_and_set(key, expected, value)

    def compare_and_delete(self, key: str, expected: bytes) -> bool:
        """Atomically deletes key if its current value matches expected.

        Returns whether the delete took place. Raises
        ``componentize_py_types.Err(str)`` if the host call fails.
        """
        return self._inner.compare_and_delete(key, expected)

    def delete(self, key: str) -> None:
        """Raises ``componentize_py_types.Err(str)`` if the host call fails."""
        self._inner.delete(key)

    def batch_set(self, entries: Dict[str, bytes]) -> None:
        """Stores multiple key/value entries in a single host call."""
        self._inner.batch_set(list(entries.items()))

    def get_range(self, start_key: str, end_key: str, limit: int, offset: int) -> Dict[str, bytes]:
        """Returns up to limit entries with keys in [start_key, end_key)."""
        return dict(self._inner.get_range(start_key, end_key, limit, offset))

    def __enter__(self) -> "Table":
        return self

    def __exit__(self, exc_type, exc_value, traceback) -> None:
        self._inner.__exit__(exc_type, exc_value, traceback)
